use std::{
    future::Future,
    pin::Pin,
    task::{ready, Context, Poll},
};

use axum_core::{body::Body, response::Response, BoxError};
use bytes::Bytes;
use http_body::Body as HttpBody;
use pin_project_lite::pin_project;
use tower::{Layer, Service};

/// Layer that transforms the Response body to [`crate::body::Body`].
///
/// This is useful when another layer maps the body to some other type to convert it back.
#[derive(Debug, Clone)]
pub struct ResponseAxumBodyLayer;

impl<S> Layer<S> for ResponseAxumBodyLayer {
    type Service = ResponseAxumBody<S>;

    fn layer(&self, inner: S) -> Self::Service {
        ResponseAxumBody::<S>(inner)
    }
}

/// Service generated by [`ResponseAxumBodyLayer`].
#[derive(Debug, Clone)]
pub struct ResponseAxumBody<S>(S);

impl<S, Request, ResBody> Service<Request> for ResponseAxumBody<S>
where
    S: Service<Request, Response = Response<ResBody>>,
    ResBody: HttpBody<Data = Bytes> + Send + 'static,
    <ResBody as HttpBody>::Error: Into<BoxError>,
{
    type Response = Response;

    type Error = S::Error;

    type Future = ResponseAxumBodyFuture<S::Future>;

    fn poll_ready(&mut self, cx: &mut Context<'_>) -> Poll<Result<(), Self::Error>> {
        self.0.poll_ready(cx)
    }

    fn call(&mut self, req: Request) -> Self::Future {
        ResponseAxumBodyFuture {
            inner: self.0.call(req),
        }
    }
}

pin_project! {
    /// Response future for [`ResponseAxumBody`].
    pub struct ResponseAxumBodyFuture<Fut> {
        #[pin]
        inner: Fut,
    }
}

impl<Fut, ResBody, E> Future for ResponseAxumBodyFuture<Fut>
where
    Fut: Future<Output = Result<Response<ResBody>, E>>,
    ResBody: HttpBody<Data = Bytes> + Send + 'static,
    <ResBody as HttpBody>::Error: Into<BoxError>,
{
    type Output = Result<Response<Body>, E>;

    fn poll(self: Pin<&mut Self>, cx: &mut Context<'_>) -> Poll<Self::Output> {
        let this = self.project();
        let res = ready!(this.inner.poll(cx)?);
        Poll::Ready(Ok(res.map(Body::new)))
    }
}

#[cfg(test)]
mod tests {
    use super::ResponseAxumBodyLayer;
    use crate::{body::Body, BoxError};
    use bytes::Bytes;
    use http::{Request, Response, StatusCode};
    use http_body::Frame;
    use http_body_util::{BodyExt, Full, StreamBody};
    use std::{convert::Infallible, io};
    use tower::{service_fn, Layer, ServiceExt};

    #[tokio::test]
    async fn accepts_boxed_body_errors() {
        let service = ResponseAxumBodyLayer.layer(service_fn(|_: Request<Body>| async {
            let body = Full::new(Bytes::from_static(b"hello"))
                .map_err(|err| -> BoxError { match err {} })
                .boxed();
            let mut response = Response::new(body);
            *response.status_mut() = StatusCode::CREATED;
            response
                .headers_mut()
                .insert("x-test", "value".parse().unwrap());
            Ok::<_, Infallible>(response)
        }));

        let response = service.oneshot(Request::new(Body::empty())).await.unwrap();

        assert_eq!(response.status(), StatusCode::CREATED);
        assert_eq!(response.headers()["x-test"], "value");
        let body = response.into_body().collect().await.unwrap().to_bytes();
        assert_eq!(body, "hello");
    }

    #[tokio::test]
    async fn preserves_boxed_body_errors() {
        let service = ResponseAxumBodyLayer.layer(service_fn(|_: Request<Body>| async {
            let stream = futures_util::stream::once(async {
                Err::<Frame<Bytes>, BoxError>(io::Error::other("body failed").into())
            });
            let body = StreamBody::new(stream).boxed_unsync();
            Ok::<_, Infallible>(Response::new(body))
        }));

        let response = service.oneshot(Request::new(Body::empty())).await.unwrap();
        let error = response.into_body().collect().await.unwrap_err();
        let error = error.into_inner().downcast::<io::Error>().unwrap();

        assert_eq!(error.to_string(), "body failed");
    }
}
